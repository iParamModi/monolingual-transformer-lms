def _generate_into(tmp_path: Path, lang: str, seed: int) -> dict[str, bytes]:
    """Run the generator into a temporary directory and return the raw files."""
    out_dir = tmp_path / f"{lang}-{seed}"
    result = subprocess.run(
        [sys.executable, "-m", "finetune.gen_reasoning",
         "--lang", lang, "--out-dir", str(out_dir), "--repo-root", str(REPO_ROOT),
         "--n-train", "300", "--n-val", "60", "--n-test", "60",
         "--seed", str(seed), "--digits", "ascii", "--no-tokenizer"],
        cwd=REPO_ROOT, capture_output=True, text=True,
        # The child prints Devanagari. Without an explicit codec, text=True
        # decodes with the locale default (cp1252 on Windows) and the reader
        # thread dies on the first Devanagari byte.
        encoding="utf-8", errors="replace",
    )
    assert result.returncode == 0, result.stdout + result.stderr
    return {p.name: p.read_bytes() for p in sorted(out_dir.iterdir())}


@pytest.mark.parametrize("lang", LANGS)
def test_generation_is_reproducible(tmp_path, lang):
    """Assertion 8: the same seed produces byte-identical files.

    Run with ``--no-tokenizer`` so the check does not depend on the Phase 1
    artifacts being present, and with an explicit digit script so it does not
    read ``train.bin``.
    """
    first = _generate_into(tmp_path, lang, 4242)
    second = _generate_into(tmp_path / "again", lang, 4242)
    assert sorted(first) == sorted(second)
    for name in sorted(first):
        assert first[name] == second[name], f"{name} differs between two identical runs"


@pytest.mark.parametrize("lang", LANGS)
def test_a_different_seed_produces_different_data(tmp_path, lang):
    """The control for the test above: seeding must actually do something."""
    first = _generate_into(tmp_path, lang, 4242)
    other = _generate_into(tmp_path / "other", lang, 99)
    assert first["train.jsonl"] != other["train.jsonl"]


# --------------------------------------------------------------------------- #
# 9. The labels are correct
# --------------------------------------------------------------------------- #


def rederive_answer(record: dict, equal_word: str) -> str:
    """Work out the correct answer from the record's stated ground truth.

    Deliberately independent of :func:`finetune.gen_reasoning.sample_example`:
    it reads ``order`` (entities from greatest to least) or ``values``, applies
    the semantics of the template family, and returns what the answer must be.
    If the generator ever mislabels an example, this disagrees.

    Args:
        record: One dataset record.
        equal_word: The language's word for "equal".

    Returns:
        The answer the record should carry.
    """
    template = record["template"]
    ask = record["ask"]

    if template == 5:
        values = record["values"]
        assert len(set(values.values())) == 1, "the equality family must have equal values"
        return equal_word

    if template == 4:
        values = record["values"]
        chooser = max if ask == "big" else min
        return chooser(sorted(values), key=lambda name: values[name])

    order = record["order"]  # greatest -> least
    if template == 6:
        return order[1]
    if template == 3:
        pair = record["pair"]
        ranked = [name for name in order if name in pair]
        return ranked[0] if ask == "big" else ranked[-1]
    # T0, T1, T2: pick a pole of the full ordering.
    return order[0] if ask == "big" else order[-1]


@pytest.mark.parametrize("lang", LANGS)
def test_labels_are_correct(lang):
    """Assertion 9: every answer is re-derivable from the stated ground truth."""
    equal_word = language_spec(lang).grammar.equal_word
    for split in SPLITS:
        for record in load_split(lang, split):
            expected = rederive_answer(record, equal_word)
            assert record["answer"] == expected, (
                f"{record['id']} (T{record['template']}, ask={record['ask']}) "
                f"is labelled {record['answer']!r} but should be {expected!r}: "
                f"{record['prompt']}"
            )


@pytest.mark.parametrize("lang", LANGS)
def test_numeric_values_are_well_separated(lang):
    """Comparisons must not hinge on a difference the model cannot resolve."""
    for split in SPLITS:
        for record in load_split(lang, split):
            if record["template"] != 4:
                continue
            values = sorted(record["values"].values())
            gaps = [b - a for a, b in zip(values, values[1:])]
            assert min(gaps) >= 3, f"{record['id']} has values {values}"


@pytest.mark.parametrize("lang", LANGS)
def test_chain_premises_do_not_state_the_asked_pair_directly(lang):
    """T3 must require transitivity, not just reading a premise back.

    The asked pair is the two *non-adjacent* entities of the chain, so no single
    premise relates them. If the pair were ever adjacent, the family would be a
    lookup rather than a reasoning step.
    """
    for record in load_split(lang, "test_templates"):
        if record["template"] != 3:
            continue
        order = record["order"]
        assert set(record["pair"]) == {order[0], order[-1]}
        assert abs(order.index(record["pair"][0]) - order.index(record["pair"][1])) > 1
